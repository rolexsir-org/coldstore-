_VEH = itertools.count(1)


def receipt_body(ids, **kw):
    body = {
        "season_id": ids["season"], "owner_id": ids["owner"], "grower_id": ids["grower"],
        # unique vehicle per receipt by default → no accidental duplicate-window tripping
        "vehicle_no": kw.pop("vehicle_no", f"JK01AB{next(_VEH):04d}"),
        "weighbridge_ref": "",
        "gross_kg": 10_000.0, "tare_kg": 600.0, "packaging_id": ids["crate"],
        "unit_count": 450, "variety_id": ids["variety"], "grade_id": ids["grade_a"],
        "harvest_year": 2026,
    }
    body.update(kw)
    return body


def make_lot(client, auth, ids, *, chamber="chamber1", net=9_400.0, verify_by="intake2",
             **kw):
    """Full happy-path: receipt (intake) → verify+allocate (intake2) → lot id."""
    r1 = client.post("/api/v1/intake/receipts", json=receipt_body(ids, **kw), headers=auth["intake"])
    assert r1.status_code == 201, r1.text
    rid = r1.json()["id"]
    r2 = client.post(f"/api/v1/intake/receipts/{rid}/verify",
                     json={"chamber_id": ids[chamber]}, headers=auth[verify_by])
    assert r2.status_code == 200, r2.text
    return r2.json()["lot_id"], r2.json()["lot_no"], rid
